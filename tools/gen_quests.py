"""Generate docs/quests/ from reference/wiki/To-Do Quests.md (progressively loadable quest docs).

- docs/quests/INDEX.md                 : all quests grouped by questline, with status + RU name + link (regenerated)
- docs/quests/<line>/<quest>.md         : one file per quest. Front matter (status, ru) and everything outside the
                                          <!-- wiki:start/end --> markers is preserved on regeneration, so verified
                                          steps written during play are never lost.
Run: python3 -I tools/gen_quests.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'reference', 'wiki', 'To-Do Quests.md')
OUT = os.path.join(ROOT, 'docs', 'quests')
WIKI = os.path.join(ROOT, 'reference', 'wiki')

# Initial status/RU names for quests already met in-game (only applied when a quest file is first created).
SEED = {
    "To Gramma's House I Go": ('done', 'В гости к бабушке'),
    'From Bud To Spud': ('active', 'Крошка-картошка'),
    'The Fungus Among Us': ('active', 'Занимательная микология'),
    'The Most Elaborate Icebreaker': ('active', 'Скоростные знакомства'),
}
BRIEF_TEMPLATE = '''## Quest brief (supervisor-maintained; the agent's single source of truth)
- **Why:** ❓
- **Steps (current → end):** ❓
- **How-to:** ❓ (see `docs/mechanics/basic-actions.md` rows)
- **Where:** ❓ (see `docs/world/locations.md`)
- **Progress signal:** ❓ (tracker text via `./wf state` → `tracker:` / journal J)
- **Done when:** ❓ · **Next after done:** ❓
- **Read:** ❓ (manifest: exact files/sections/commands the agent needs)
- **Tips:** ❓ tags → `./wf tips <tags>`
- **Gotchas:** —
'''
STATUS_ICON = {'done': '✅', 'active': '▶️', 'todo': '·'}


def slug(s):
    s = s.lower().replace('’', '').replace("'", '')
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')


def parse():
    lines = open(SRC).read().split('\n')
    quests, line, season = [], None, ''
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith('## '):
            line, season = ln[3:].strip().replace(' Quests', ''), ''
        elif ln.startswith('### '):
            season = ln[4:].strip()
        elif line and i + 1 < len(lines) and lines[i + 1].startswith('| Description') and ln.strip() \
                and not ln.startswith('|'):
            body = []
            j = i + 1
            while j < len(lines):
                nxt = lines[j]
                if nxt.startswith('#') or (j + 1 < len(lines) and lines[j + 1].startswith('| Description')
                                           and nxt.strip() and not nxt.startswith('|')):
                    break
                body.append(nxt)
                j += 1
            quests.append({'name': ln.strip(), 'line': line, 'season': season, 'body': '\n'.join(body).strip()})
            i = j
            continue
        i += 1
    return quests


def summary(body):
    rows = [r for r in body.split('\n') if r.startswith('| ') and not r.startswith('| Description')]
    if not rows:
        return ''
    cells = [c.strip() for c in rows[0].strip('|').split('|')]
    giver = re.sub(r'\S+\.(png|jpg)\s*', '', cells[1]).strip() if len(cells) > 1 else ''
    giver = ' '.join(dict.fromkeys(giver.split()))  # wiki repeats names ("Bruno Soft Bruno Soft")
    return f'{cells[0]} (from {giver}; {len(rows)} step(s))' if giver else cells[0]


def read_front(path):
    meta, rest = {}, ''
    if os.path.exists(path):
        txt = open(path).read()
        m = re.match(r'---\n(.*?)\n---\n(.*)', txt, re.S)
        if m:
            for l in m.group(1).split('\n'):
                if ':' in l:
                    k, v = l.split(':', 1)
                    meta[k.strip()] = v.split('#')[0].strip()
            rest = m.group(2)
    return meta, rest


def main():
    quests = parse()
    index = {}
    for q in quests:
        d = os.path.join(OUT, slug(q['line']))
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, slug(q['name']) + '.md')
        meta, rest = read_front(path)
        st, ru = SEED.get(q['name'], ('todo', ''))
        meta.setdefault('status', st)
        meta.setdefault('ru', ru)
        wiki_page = q['name'] + '.md'
        wiki_ref = f'reference/wiki/{wiki_page}' if os.path.exists(os.path.join(WIKI, wiki_page)) else '—'
        gen = (f'<!-- wiki:start (generated by tools/gen_quests.py, do not edit inside) -->\n'
               f'**Wiki page:** `{wiki_ref}`\n\n{q["body"]}\n<!-- wiki:end -->')
        if rest and '<!-- wiki:start' in rest:
            rest = re.sub(r'<!-- wiki:start.*?<!-- wiki:end -->', lambda _: gen, rest, flags=re.S)
        else:
            title = q['name'] + (f' ({meta["ru"]})' if meta['ru'] else '')
            rest = (f'# {title}\n\n> **Summary:** {summary(q["body"])}\n\n'
                    f'{BRIEF_TEMPLATE}\n'
                    f'## Wiki requirements\n{gen}\n\n'
                    f'## Verified steps\n_Not played yet. Record AS YOU GO under `### Attempt N (<day/time>)`: ✅ worked '
                    f'(exact `./wf` commands → what appears, RU + EN) · ❌ dead end (why) · ❓ open question/gap._\n')
        front = (f'---\nquest: {q["name"]}\nru: {meta["ru"]}\nline: {q["line"]}\nseason: {q["season"]}\n'
                 f'status: {meta["status"]}   # todo | active | done\n---\n')
        open(path, 'w').write(front + rest)
        index.setdefault(q['line'], []).append((q, meta, os.path.relpath(path, OUT)))

    out = ['# Quests index (generated by tools/gen_quests.py; status/RU come from each quest file\'s front matter)',
           '',
           'Load order: this index → the one quest file you need. Statuses: ▶️ active · ✅ done · · todo.',
           'To change a status or add the RU name, edit the quest file front matter and re-run the generator.', '']
    active = [(q, m, p) for qs in index.values() for q, m, p in qs if m['status'] == 'active']
    out += ['## ▶️ Active now', ''] + [f'- [{q["name"]}]({p}) — {m["ru"]} · {q["line"]}' for q, m, p in active] + ['']
    for line, qs in index.items():
        done = sum(1 for _, m, _ in qs if m['status'] == 'done')
        out += [f'## {line} ({done}/{len(qs)} done)', '', '| | Quest | RU | Season | Summary |', '|---|---|---|---|---|']
        for q, m, p in qs:
            out.append(f'| {STATUS_ICON.get(m["status"], "·")} | [{q["name"]}]({p}) | {m["ru"]} | {q["season"]} | '
                       f'{summary(q["body"])[:90].replace("|", "/")} |')
        out.append('')
    open(os.path.join(OUT, 'INDEX.md'), 'w').write('\n'.join(out))
    print(f'{len(quests)} quests in {len(index)} questlines')


if __name__ == '__main__':
    main()
