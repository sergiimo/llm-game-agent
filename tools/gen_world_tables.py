"""Generate aggregate indexes from the manifest-backed unified Wiki."""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIKI = os.path.join(ROOT, 'wiki')
OUT = WIKI
MANIFEST = json.load(open(os.path.join(WIKI, 'manifest.json')))
PAGES = {a: p['canonical_path'] for p in MANIFEST['pages'] for a in p['aliases']}


def read(name):
    p = os.path.join(ROOT, PAGES.get(name, ''))
    return open(p).read() if os.path.exists(p) else ''


def infobox(text, box='Character'):
    m = re.search(r'^\[' + box + r'\]\n((?:  .*\n(?:[^\[\n#].*\n)*)+)', text, re.M)
    fields = {}
    if not m:
        return fields
    key = None
    for line in m.group(1).split('\n'):
        km = re.match(r'  (\w+): ?(.*)', line)
        if km:
            key = km.group(1)
            fields[key] = km.group(2).strip()
        elif key and line.strip():
            fields[key] += ' ' + line.strip()
    return fields


def one_line(s, n=160):
    s = re.sub(r'(?i)<br\s*/?>|</br>', '; ', s or '')
    s = re.sub(r'\s+', ' ', s).strip(' ;*')
    s = s.replace('|', '/')
    return s if len(s) <= n else s[:n - 1] + '…'


def favorite_gifts():
    favs = {}
    txt = read('Gifting')
    for m in re.finditer(r'\|  \|\n(.+?)\n\| (.+?) \|\n', txt):
        name = m.group(1).strip()
        items = [re.sub(r'^.*\.jpg ', '', i).strip() for i in m.group(2).split(' | ')]
        items = [re.sub(r'^(.+) \1$', r'\1', i) for i in items if i]
        favs[name] = ', '.join(items)
    return favs


def characters():
    favs = favorite_gifts()
    names = sorted(n for n in PAGES if '__' not in n and '[Character]' in read(n))
    rows = []
    for n in names:
        f = infobox(read(n))
        cs = infobox(read(n), 'CharacterSetUp')
        rows.append('| {} | {} | {} | {} | {} | {} | {} |'.format(
            n, one_line(f.get('occupation'), 60), one_line(f.get('workplace'), 50),
            one_line(f.get('residence'), 60), one_line(f.get('romance'), 10),
            one_line(cs.get('MonPersonal'), 140), one_line(favs.get(n) or favs.get(n.split()[0]), 120)))
    hdr = ('# Characters of Fairhaven (generated)\n\n'
           'Generated by `tools/gen_world_tables.py` from the fan wiki. Full per-character pages, schedules, '
           'heart events and dialogues: `./wf wiki "<Name>"`, `<Name>__Schedule.md`, `<Name>__Events.md`.\n\n'
           '| Name | Occupation | Workplace | Residence | Romance | Where/when (wiki note) | Favorite gifts |\n'
           '|---|---|---|---|---|---|---|\n')
    open(os.path.join(OUT, 'characters', 'INDEX.md'), 'w').write(hdr + '\n'.join(rows) + '\n')


