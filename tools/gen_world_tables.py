def businesses():
    rows = []
    for name, owner, what in BUSINESSES:
        txt = read(name)
        hours = re.findall(r'^\| (?:<b>)? ?([A-Z][a-z]{2}[a-z\-A-Z ]*?) \| ([^|]+?) \|$', txt, re.M)
        hours = [(d, t) for d, t in hours if re.match(r'(?i)\s*(closed|\d{1,2}(:\d\d)?\s*[ap]m)', t)]
        h = '; '.join(f'{d.strip()} {t.strip()}' for d, t in hours) or '?'
        rows.append(f'| {name} | {owner} | {h} | {what} |')
    hdr = ('# Businesses & opening hours (generated)\n\n'
           'Inventory, unlock levels and prices: `./wf wiki "<Business>"`. Selling items to a shop raises its '
           'level (stars, top-right of the shop window) and unlocks more stock.\n\n'
           '| Business | Owner | Hours | Buys / sells |\n|---|---|---|---|\n')
    open(os.path.join(OUT, 'businesses', 'INDEX.md'), 'w').write(hdr + '\n'.join(rows) + '\n')


ITEM_BOXES = {
    'Crops': 'crops', 'Seeds': 'seeds', 'Forage': 'forage', 'Fish': 'fish', 'Food': 'food',
    'Crafting Ingredient': 'ingredients', 'Potions Incantations': 'potions',
    'Workstation': 'workstations', 'Tool': 'tools', 'Book': 'books', 'Item': 'misc', 'Magic_Items': 'misc',
}
ITEM_COLS = [('recipe', 'Recipe'), ('workstation', 'Made at'), ('category', 'Category/station'),
             ('craftingTime', 'Time'), ('growthTime', 'Grow'), ('season', 'Season'), ('location', 'Where'),
             ('bait', 'Bait'), ('source', 'Source'), ('buyPrice', 'Buy'), ('sellPrice', 'Sell'), ('sellTo', 'Sell to'),
             ('use', 'Use'), ('unlockRequirements', 'Unlock'), ('recipeSource', 'Recipe from'),
             ('personsFavorite', 'Favorite of')]


def items():
    groups = {}
    for name in sorted(PAGES):
        if '__' in name:
            continue
        txt = read(name)
        for box, slug in ITEM_BOXES.items():
            if '[' + box + ']\n' in txt:
                fields = infobox(txt, re.escape(box))
                fields.setdefault('itemName', name)
                groups.setdefault(slug, []).append((name, fields))
                break
    os.makedirs(os.path.join(OUT, 'items'), exist_ok=True)
    for slug, entries in groups.items():
        cols = [c for c in ITEM_COLS if any(e[1].get(c[0]) for e in entries)]
        lines = [f'# {slug.replace("-", " ").title()} (generated, {len(entries)} entries)\n',
                 'Source: fan wiki infoboxes via `tools/gen_world_tables.py`. Details: `./wf wiki "<Name>"`.\n',
                 '| Name | ' + ' | '.join(c[1] for c in cols) + ' |',
                 '|---|' + '---|' * len(cols)]
        for page, fl in entries:
            lines.append('| ' + page + ' | ' + ' | '.join(one_line(fl.get(k), 110) for k, _ in cols) + ' |')
        os.makedirs(os.path.join(OUT, 'items', slug), exist_ok=True)
        open(os.path.join(OUT, 'items', slug, 'INDEX.md'), 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    characters()
    businesses()
    items()
    print('ok', file=sys.stderr)
